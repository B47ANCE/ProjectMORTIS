local Context = {}

function Context.create(zombie, typeDef)
    return {
        zombie = zombie,
        type = typeDef or Identity.getType(zombie),
        components = Components,
        authority = Authority,
        capabilities = Capabilities,
        scheduler = Scheduler,
        random = Random,
        profiler = Profiler,
        log = Logger,
        target = Target,
        navigation = Navigation,
        locomotion = Locomotion,
        combat = Combat,
        durability = Durability,
        obstacles = Obstacles,
        environment = Environment,
        animation = Animation,
        state = State,
        appearance = Appearance,
        network = Network,
        sound = Sound,
        groups = Groups,
        spawn = Spawn,
        profiles = Profiles,
        damage = DamageRuntime,
        collision = Collision,
        trip = Trip,
        anatomy = Anatomy,
        trauma = Trauma,
        entity = Entity,
        hitLocation = HitLocation,
        weapon = Weapon,
        hitTrauma = HitTrauma,
        weaponCatalog = WeaponCatalog,
        physical = PhysicalInteractions,
        physicalEnvironment = PhysicalEnvironment,
        balance = Balance,
        stomp = StompRuntime,
        shove = ShoveRuntime,
        physicalSettings = PhysicalSettings,
        ragdoll = Ragdoll,
    }
end

return Context
